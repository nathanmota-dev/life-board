test("tasks: pointer reorder persists", async ({ workspace, page }) => {
  await workspace.create("tasks", { title: "First card" })
  await workspace.create("tasks", { title: "Second card" })
  await workspace.go("Tarefas")
  const first = page.getByRole("article", { name: "First card" })
  const second = page.getByRole("article", { name: "Second card" })
  const before = (await workspace.list<Task>("tasks")).map(task => [task.id, task.order])
  await drag(page, first, second)
  await expect.poll(async () => (await workspace.list<Task>("tasks")).map(task => [task.id, task.order])).not.toEqual(before)
  await page.reload()
  await expect(first).toBeVisible()
  await expect(second).toBeVisible()
})
