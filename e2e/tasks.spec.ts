test("tasks: pin, color, due date and combined search filters", async ({ workspace, page }) => {
  await workspace.create("tasks", { title: "Filter target", status: "today", tags: ["work"] })
  await workspace.create("tasks", { title: "Other task", status: "someday", tags: ["home"] })
  await workspace.go("Tarefas")
  const card = page.getByRole("article", { name: "Filter target" })
  await card.getByRole("button", { name: "Fixar", exact: true }).click()
  await expect(card.getByRole("button", { name: "Desafixar", exact: true })).toBeVisible()
  await card.getByRole("button", { name: "Cor", exact: true }).click()
  await page.getByRole("button", { name: "Azul", exact: true }).click()
  await page.keyboard.press("Escape")
  await card.getByRole("button", { name: "Data de vencimento" }).click()
  await page.locator('input[type="date"]').fill("2026-10-20")
  await page.keyboard.press("Escape")
  await page.getByRole("button", { name: "Atrasadas", exact: true }).click()
  await choose(page, "Filtrar por tag", "#work")
  await page.getByRole("button", { name: "Filtrar por cor" }).click()
  await page.getByRole("button", { name: "Azul", exact: true }).click()
  await page.keyboard.press("Escape")
  await page.getByPlaceholder("Buscar tarefas").fill("Filter")
  await expect(card).toBeVisible()
  await expect(page.getByRole("article", { name: "Other task" })).toHaveCount(0)
  await page.getByPlaceholder("Buscar tarefas").fill("missing")
  await expect(page.getByText("Nenhuma tarefa corresponde a estes filtros", { exact: true })).toBeVisible()
  expect((await workspace.list<Task>("tasks")).find(task => task.title === "Filter target")).toMatchObject({ color: "blue", pinned: true })
})

