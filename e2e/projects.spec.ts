import { test, expect } from "./fixtures"
import { choose, closeDialog, drag } from "./ui"
import type { Project } from "../web/src/types/project"

test("projects: form, quick add, editing, pause reason and history", async ({ workspace, page }) => {
  await workspace.go("Projetos")
  await page.getByRole("button", { name: "Novo projeto", exact: true }).first().click()
  await page.getByLabel("Título", { exact: true }).fill("Build a desk")
  await page.getByLabel("Descrição", { exact: true }).fill("Woodworking project")
  await page.getByRole("button", { name: "Adicionar projeto", exact: true }).click()
  await page.getByRole("textbox", { name: "Nova ideia", exact: true }).fill("Quick idea")
  await page.getByRole("textbox", { name: "Nova ideia", exact: true }).press("Enter")
  await expect(page.getByRole("heading", { name: "Quick idea", exact: true })).toBeVisible()
  await page.getByRole("heading", { name: "Build a desk", exact: true }).click()
  await page.getByRole("button", { name: "Editar projeto", exact: true }).click()
  await page.getByLabel("Título", { exact: true }).fill("Build a table")
  await page.getByRole("button", { name: "Salvar", exact: true }).click()
  await page.locator("#project-detail-status").click()
  await page.getByRole("option", { name: "Pausado", exact: true }).click()
  await page.getByLabel("Motivo da pausa", { exact: true }).fill("Waiting for wood")
  await page.getByRole("button", { name: "Pausar", exact: true }).click()
  await expect(page.getByRole("dialog")).toContainText("Waiting for wood")
  await expect(page.getByRole("dialog")).toContainText("Histórico de status")
  await closeDialog(page)
  await page.reload()
  await expect(page.getByRole("region", { name: "Pausado", exact: true })).toContainText("Build a table")
})

test("projects: pointer move, WIP warning and persisted limit", async ({ workspace, page }) => {
  await workspace.create("projects", { title: "Move project", status: "idea" })
  await workspace.create("projects", { title: "Existing project", status: "in_progress" })
  await workspace.go("Projetos")
  await page.getByRole("button", { name: "Limite de projetos em andamento", exact: true }).click()
  await page.getByRole("spinbutton", { name: "Limite de projetos em andamento", exact: true }).fill("1")
  await page.keyboard.press("Escape")
  await drag(page, page.getByRole("heading", { name: "Move project", exact: true }), page.getByRole("region", { name: "Em andamento", exact: true }).getByRole("article").first())
  await expect.poll(async () => (await workspace.list<Project>("projects")).find(project => project.title === "Move project")?.status).toBe("in_progress")
  await expect(page.getByText("Acima do limite de 1 projetos em andamento", { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole("button", { name: "Limite de projetos em andamento", exact: true })).toContainText("Limite 1")
})

test("projects: completed expansion, archive, restore and deletion undo", async ({ workspace, page }) => {
  for (let i = 0; i < 7; i++) await workspace.create("projects", { title: `Done project ${i}`, status: "done" })
  await workspace.go("Projetos")
  await page.getByRole("button", { name: "Mostrar todos (7)", exact: true }).click()
  await expect(page.getByRole("region", { name: "Concluído", exact: true }).getByRole("article")).toHaveCount(7)
  await page.getByRole("button", { name: "Mostrar menos", exact: true }).click()
  await page.getByRole("button", { name: "Mostrar todos (7)", exact: true }).click()
  await page.getByRole("button", { name: "Ações de Done project 0" }).click()
  await page.getByRole("menuitem", { name: "Arquivar", exact: true }).click()
  await page.getByRole("tab", { name: "Arquivados", exact: true }).click()
  await page.getByRole("button", { name: "Restaurar Done project 0" }).click()
  await page.getByRole("tab", { name: /^Quadro/ }).click()
  await page.getByRole("button", { name: "Mostrar todos (7)", exact: true }).click()
  await page.getByRole("button", { name: "Ações de Done project 0" }).click()
  await page.getByRole("menuitem", { name: "Excluir", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Done project 0", exact: true })).toHaveCount(0)
  await page.locator("[data-sonner-toast]").filter({ hasText: "“Done project 0” excluído" }).getByRole("button", { name: "Desfazer", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Done project 0", exact: true })).toBeVisible()
})
