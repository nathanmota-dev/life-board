test("goals: task and habit completion changes automatic progress, manual mode persists", async ({ workspace, page }) => {
  const task = await workspace.create("tasks", { title: "Progress task", status: "today" })
  const habit = await workspace.create("habits", { name: "Progress habit", target: 1 })
  const { goal } = await workspace.create<{ goal: Goal }>("goals", { title: "Progress goal", linkedTaskIds: [task.id], linkedHabitIds: [habit.id], milestones: [{ title: "Progress milestone" }] })
  await workspace.go("Metas")
  await page.getByRole("button", { name: /Progress goal/ }).click()
  await page.getByRole("checkbox", { name: "Concluir Progress milestone" }).click()
  await closeDialog(page)
  await workspace.go("Tarefas")
  await page.getByRole("article", { name: "Progress task" }).getByRole("button", { name: "Marcar como concluída" }).click()
  await workspace.go("Hábitos")
  await page.getByRole("button", { name: "Registrar Progress habit", exact: true }).click()
  await workspace.go("Metas")
  await page.getByRole("button", { name: /Progress goal/ }).click()
  await expect(page.getByRole("progressbar", { name: "Progresso da meta", exact: true })).toHaveAttribute("aria-valuenow", "100")
  await page.getByRole("tab", { name: "Manual", exact: true }).click()
  await page.getByRole("spinbutton", { name: /Progresso digitado à mão/ }).fill("42")
  await page.getByRole("spinbutton", { name: /Progresso digitado à mão/ }).press("Tab")
  await expect.poll(async () => (await workspace.api.get(`goals/${goal.id}`).then(response => response.json())).goal.progress).toBe(42)
  await closeDialog(page)
  await page.reload()
  await page.getByRole("button", { name: /Progress goal/ }).click()
  await expect(page.getByRole("spinbutton", { name: /Progresso digitado à mão/ })).toHaveValue("42")
  await page.getByRole("tab", { name: "Automático", exact: true }).click()
  await expect(page.getByRole("progressbar", { name: "Progresso da meta", exact: true })).toHaveAttribute("aria-valuenow", "100")
})

test("goals: every status and progress history survive UI changes", async ({ workspace, page }) => {
  const { goal } = await workspace.create<{ goal: Goal }>("goals", { title: "Goal lifecycle" })
  await workspace.go("Metas")
  await page.getByRole("button", { name: /Goal lifecycle/ }).click()
  for (const [label, status] of [["Pausada", "paused"], ["Concluída", "completed"], ["Abandonada", "abandoned"], ["Ativa", "active"]]) {
    await page.locator("#goal-status").click()
    await page.getByRole("option", { name: label, exact: true }).click()
    await expect(page.locator("#goal-status")).toContainText(label)
    const detail = await workspace.api.get(`goals/${goal.id}`).then(response => response.json())
    expect(detail.goal.status).toBe(status)
    if (status === "completed") expect(detail.goal.completedAt).not.toBeNull()
    else expect(detail.goal.completedAt).toBeNull()
  }
  await page.getByRole("tab", { name: "7 dias", exact: true }).click()
  await expect(page.getByRole("application")).toBeVisible()
  expect((await workspace.api.get(`goals/${goal.id}/progress`).then(response => response.json())).items.length).toBeGreaterThan(0)
})

test("goals: status and area filters, grouping, timeline and risk indicators", async ({ workspace, page }) => {
  await workspace.create("goals", { title: "Overdue health", domain: "health", startAt: "2026-10-01T00:00:00Z", targetAt: "2026-10-20T00:00:00Z" })
  await workspace.create("goals", { title: "Career without deadline", domain: "career" })
  await workspace.go("Metas")
  await expect(page.getByText("Atrasada", { exact: true }).first()).toBeVisible()
  await page.getByRole("button", { name: "Agrupar por área", exact: true }).click()
  await page.getByRole("button", { name: "Saúde", exact: true }).click()
  await expect(page.getByRole("button", { name: /Career without deadline/ })).toHaveCount(0)
  await page.getByRole("button", { name: "Todas as áreas", exact: true }).click()
  await page.getByRole("tab", { name: "Linha do tempo", exact: true }).click()
  await expect(page.getByText("Sem data alvo", { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole("tab", { name: "Linha do tempo", exact: true })).toHaveAttribute("aria-selected", "true")
  await page.getByRole("button", { name: /Career without deadline/ }).click()
  await page.locator("#goal-status").click()
  await page.getByRole("option", { name: "Pausada", exact: true }).click()
  await closeDialog(page)
  await page.getByRole("tab", { name: /^Pausada/ }).click()
  await expect(page.getByText("Career without deadline", { exact: true })).toBeVisible()
  await expect(page.getByText("Overdue health", { exact: true })).toHaveCount(0)
})
