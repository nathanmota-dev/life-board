import { test, expect } from "./fixtures"
import { closeDialog } from "./ui"

test("thoughts: create, link, pin, search, edit and delete; backlinks and tags update", async ({ workspace, page }) => {
  await workspace.create("tasks", { title: "Linked task", tags: ["shared"] })
  await workspace.go("Ideias")
  await page.getByRole("button", { name: "Nova ideia", exact: true }).click()
  await page.getByLabel("Título", { exact: true }).fill("Linked thought")
  await page.getByLabel("Ideia", { exact: true }).fill("Thought body")
  await page.getByRole("textbox", { name: "Etiquetas", exact: true }).fill("shared, idea")
  await page.getByRole("checkbox", { name: "Fixar no topo" }).click()
  await page.getByRole("button", { name: "Vincular tarefas", exact: true }).click()
  await page.getByRole("checkbox", { name: "Linked task", exact: true }).click()
  await page.keyboard.press("Escape")
  await page.getByRole("button", { name: "Salvar ideia", exact: true }).click()
  await expect(page.getByRole("button", { name: "Linked thought", exact: true })).toBeVisible()
  await page.getByRole("tab", { name: "Fixadas", exact: true }).click()
  await page.getByPlaceholder("Buscar ideias").fill("Linked")
  await page.getByRole("button", { name: "Linked thought", exact: true }).click()
  await expect(page.getByLabel("Ideia", { exact: true })).toHaveValue("Thought body")
  await page.getByLabel("Ideia", { exact: true }).fill("Edited thought body")
  await page.getByRole("button", { name: "Salvar", exact: true }).click()
  await workspace.go("Tarefas")
  await page.getByRole("button", { name: "Linked task", exact: true }).click()
  await expect(page.getByRole("dialog")).toContainText("Linked thought")
  await closeDialog(page)
  await workspace.go("Etiquetas")
  await page.getByPlaceholder("Filtrar etiquetas").fill("shared")
  await page.getByRole("button", { name: /shared/ }).click()
  await expect(page.getByText("Linked task", { exact: true })).toBeVisible()
  await expect(page.getByText("Linked thought", { exact: true })).toBeVisible()
  await workspace.go("Ideias")
  await page.getByRole("button", { name: "Ações de Linked thought" }).click()
  await page.getByRole("menuitem", { name: "Desafixar", exact: true }).click()
  await page.getByRole("button", { name: "Ações de Linked thought" }).click()
  await page.getByRole("menuitem", { name: "Excluir", exact: true }).click()
  await expect(page.getByRole("button", { name: "Linked thought", exact: true })).toHaveCount(0)
  await workspace.go("Etiquetas")
  await expect(page.getByRole("button", { name: /idea/ })).toHaveCount(0)
})

test("thoughts: pagination loads additional records without duplicates", async ({ workspace, page }) => {
  for (let i = 0; i < 26; i++) await workspace.create("thoughts", { title: `Thought ${String(i).padStart(2, "0")}`, body: `Body ${i}` })
  await workspace.go("Ideias")
  await expect(page.getByRole("article")).toHaveCount(24)
  await page.getByRole("button", { name: "Carregar mais", exact: true }).click()
  await expect(page.getByRole("article")).toHaveCount(26)
  await expect(page.getByRole("button", { name: "Carregar mais", exact: true })).toHaveCount(0)
})

test("activity: actions across domains produce timeline entries and weekly counts", async ({ workspace, page }) => {
  await workspace.create("tasks", { title: "Activity task", status: "done" })
  await workspace.create("thoughts", { title: "Activity thought", body: "Timeline note" })
  await workspace.create("goals", { title: "Activity goal" })
  await workspace.create("mood/entries", { score: 5, note: "Activity mood" })
  await workspace.go("Atividade")
  for (const text of ["Activity task", "Activity thought", "Activity goal", "Activity mood"]) await expect(page.getByText(text, { exact: true }).first()).toBeVisible()
  await expect(page.getByText("Tarefas concluídas", { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText("Activity task", { exact: true }).first()).toBeVisible()
})
