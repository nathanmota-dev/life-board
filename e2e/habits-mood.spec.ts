  await page.getByRole("button", { name: "Editar Backfill water em terça-feira, 20 de outubro", exact: true }).click()
  await page.getByRole("button", { name: "Adicionar 1 vezes", exact: true }).click()
  await expect(page.getByText("Parciais · 1 / 2 vezes", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Marcar meta atingida", exact: true }).click()
  await page.getByRole("button", { name: "Salvar", exact: true }).click()
