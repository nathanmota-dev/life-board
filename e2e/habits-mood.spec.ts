  await expect(tracker.getByRole("button", { name: /^Editar Backfill water em segunda-feira, 19 de outubro · Parciais/ })).toBeVisible()
  await page.getByRole("button", { name: "Semana anterior", exact: true }).click()
  await expect(tracker.getByRole("button", { name: /^Editar Backfill water em domingo, 11 de outubro · / })).toBeEnabled()
  await page.getByRole("button", { name: "Hoje", exact: true }).click()
