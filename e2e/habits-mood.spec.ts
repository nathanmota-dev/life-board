  await expect(page.getByRole("heading", { name: "Acompanhamento semanal", exact: true })).toBeVisible()
  const tracker = page.getByRole("table", { name: /^Esqueceu de registrar/ })
  await expect(tracker.getByRole("button", { name: /^Editar Backfill water em quinta-feira, 22 de outubro/ })).toBeDisabled()
  await tracker.getByRole("button", { name: /^Editar Backfill water em segunda-feira, 19 de outubro · / }).click()
