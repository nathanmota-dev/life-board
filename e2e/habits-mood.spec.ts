import { test, expect, DAY } from "./fixtures"
import type { Habit } from "../web/src/types/habit"

test("habits: personalized goal, check-ins, undo, filters, editing and deletion", async ({ workspace, page }) => {
  await workspace.go("Hábitos")
  await page.getByRole("button", { name: "Novo hábito", exact: true }).click()
  await page.getByLabel("Nome", { exact: true }).fill("Drink water")
  await page.getByLabel("Emoji", { exact: true }).fill("💧")
  await page.getByLabel("Meta diária", { exact: true }).fill("1000")
  await page.getByLabel("Unidade", { exact: true }).fill("ml")
  await page.getByLabel("Quantidade por registro", { exact: true }).fill("500")
  await expect(page.getByText("2 registros para atingir sua meta diária", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Adicionar hábito", exact: true }).click()
  await page.getByRole("button", { name: "Registrar Drink water", exact: true }).click()
  await expect(page.getByText("500 / 1000 ml", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Registrar Drink water", exact: true }).click()
  await expect(page.getByText("1000 / 1000 ml", { exact: true })).toBeVisible()
  await page.getByRole("tab", { name: /^Concluídos/ }).click()
  await expect(page.getByRole("heading", { name: "Drink water", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Desfazer Drink water", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Drink water", exact: true })).toHaveCount(0)
  await page.getByRole("tab", { name: /^Pendentes/ }).click()
  await page.getByRole("button", { name: "Ações de Drink water" }).click()
  await page.getByRole("menuitem", { name: "Editar", exact: true }).click()
  await expect(page.getByLabel("Emoji", { exact: true })).toHaveValue("💧")
  await page.getByLabel("Nome", { exact: true }).fill("Daily water")
  await page.getByLabel("Meta diária", { exact: true }).fill("1500")
  await page.getByRole("button", { name: "Salvar", exact: true }).click()
  await workspace.restart()
  page = workspace.page
  await workspace.go("Hábitos")
  await expect(page.getByText("500 / 1500 ml", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Ações de Daily water" }).click()
  await page.getByRole("menuitem", { name: "Excluir", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Daily water", exact: true })).toHaveCount(0)
  expect(await workspace.list<Habit>("habits")).toHaveLength(0)
})

test("habits: weekly, monthly and custom history with habit filter and invalid range", async ({ workspace, page }) => {
  const water = await workspace.create("habits", { name: "History water", target: 2 })
  await workspace.create("habits", { name: "History reading", target: 10, unit: "pages" })
  await workspace.create(`habits/${water.id}/logs`, { delta: 1, day: DAY })
  await workspace.go("Hábitos")
  await page.getByRole("combobox", { name: "Filtrar por hábito", exact: true }).selectOption({ label: "🌱 History water" })
  await page.getByRole("tab", { name: "30 dias", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Histórico dia a dia", exact: true })).toBeVisible()
  await page.getByRole("tab", { name: "Personalizado", exact: true }).click()
  await page.getByLabel("De", { exact: true }).fill("2026-10-20")
  await page.getByLabel("Até", { exact: true }).fill(DAY)
  await expect(page.getByRole("table")).toContainText("History water")
  await expect(page.getByRole("table")).not.toContainText("History reading")
  await page.getByLabel("De", { exact: true }).fill("2026-10-22")
  await expect(page.getByRole("alert")).toContainText("Escolha um intervalo válido")
})

test("mood: save, update and delete today's entry and dashboard reflection", async ({ workspace, page }) => {
  await workspace.go("Humor")
  await expect(page.getByRole("button", { name: "Salvar humor", exact: true })).toBeDisabled()
  await page.getByRole("radio", { name: "Bom", exact: true }).click()
  await page.getByRole("textbox", { name: "Anotação", exact: true }).fill("A good day")
  await page.getByRole("button", { name: "Salvar humor", exact: true }).click()
  await expect(page.getByRole("cell", { name: "A good day", exact: true })).toBeVisible()
  await page.getByRole("radio", { name: "Ótimo", exact: true }).click()
  await page.getByRole("textbox", { name: "Anotação", exact: true }).fill("An excellent day")
  await page.getByRole("button", { name: "Atualizar", exact: true }).click()
  await expect(page.getByRole("cell", { name: "An excellent day", exact: true })).toBeVisible()
  expect(await workspace.list("mood/entries")).toHaveLength(1)
  await workspace.go("Painel")
  await expect(page.getByText("Registrado hoje", { exact: true }).first()).toBeVisible()
  await workspace.go("Humor")
  await page.getByRole("button", { name: /^Excluir registro de/ }).click()
  await expect(page.getByText("Nenhum registro ainda", { exact: true })).toBeVisible()
  await expect(page.getByRole("button", { name: "Salvar humor", exact: true })).toBeVisible()
})
