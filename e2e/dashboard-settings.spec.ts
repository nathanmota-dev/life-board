test("shell: palette, keyboard, history, breadcrumbs and narrow sidebar", async ({ workspace, page }) => {
  await page.keyboard.press("Control+k")
  await page.getByRole("combobox", { name: "Buscar páginas", exact: true }).fill("Tarefas")
  await page.keyboard.press("Enter")
  await workspace.ready("Tarefas")
  await expect(page.getByRole("navigation", { name: "Caminho da página" })).toContainText("Tarefas")
  await page.keyboard.press("Control+k")
  await page.getByRole("combobox", { name: "Buscar páginas", exact: true }).fill("no such page")
  await expect(page.getByText("Nenhuma página encontrada.", { exact: true })).toBeVisible()
  await page.keyboard.press("Escape")
  await workspace.go("Calendário")
  await page.goBack()
  await workspace.ready("Tarefas")
  await page.goForward()
  await workspace.ready("Calendário")
  await workspace.app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(640, 800))
  await workspace.go("Configurações")
  await expect(page.getByRole("tab", { name: "Geral", exact: true })).toBeVisible()
})

test("dashboard: customize order, visibility, quick capture, persistence and reset", async ({ workspace, page }) => {
  await page.getByRole("button", { name: "Personalizar", exact: true }).click()
  await page.getByRole("checkbox", { name: "Mostrar Captura rápida", exact: true }).click()
  await page.getByRole("button", { name: "Mover Foco do dia para cima", exact: true }).click()
  await page.keyboard.press("Escape")
  await expect(page.getByRole("textbox", { name: "Texto da captura" })).toBeVisible()
  const headings = () => page.locator("main h2").allTextContents()
  expect((await headings()).indexOf("Foco do dia")).toBeLessThan((await headings()).indexOf("Meu dia"))
  await page.reload()
  await expect(page.getByRole("textbox", { name: "Texto da captura" })).toBeVisible()
  await page.getByRole("button", { name: "Personalizar", exact: true }).click()
  for (const name of ["Meu dia", "Foco do dia", "Hábitos", "Humor", "Metas ativas"]) await page.getByRole("checkbox", { name: `Mostrar ${name}`, exact: true }).click()
  await page.keyboard.press("Escape")
  await expect(page.getByText("Todos os widgets estão ocultos", { exact: true })).toBeVisible()
  await page.locator("main").getByRole("button", { name: "Restaurar layout", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Meu dia", exact: true })).toBeVisible()
  await expect(page.getByRole("textbox", { name: "Texto da captura" })).toHaveCount(0)
})

test("dashboard: focus limit, completion, removal and yesterday rollover", async ({ workspace, page }) => {
  for (let i = 1; i <= 4; i++) await workspace.create("tasks", { title: `Focus ${i}`, status: "today" })
  await workspace.create("tasks", { title: "Yesterday focus", status: "today", focusDay: "2026-10-20" })
  await page.reload()
  await page.getByRole("button", { name: "Manter", exact: true }).click()
  const focus = panel(page, "Foco do dia")
  await expect(focus).toContainText("Yesterday focus")
  await page.getByRole("button", { name: /^Escolher foco/ }).click()
  await page.getByRole("textbox", { name: "Buscar tarefas", exact: true }).fill("Focus")
  await page.getByRole("button", { name: "Adicionar Focus 1 ao foco de hoje", exact: true }).click()
  await page.getByRole("button", { name: "Adicionar Focus 2 ao foco de hoje", exact: true }).click()
  await expect(page.getByRole("button", { name: "Adicionar Focus 3 ao foco de hoje", exact: true })).toBeDisabled()
  await page.keyboard.press("Escape")
  await focus.getByRole("checkbox", { name: "Concluir Focus 1", exact: true }).click()
  await focus.getByRole("button", { name: "Remover Focus 2 do foco de hoje", exact: true }).click()
  await expect(focus.getByText("Focus 2", { exact: true })).toHaveCount(0)
  const selected = await workspace.list(`tasks?focusDay=${DAY}`)
  expect(selected).toHaveLength(2)
})

test("settings: theme, accent, languages, tabs and persistence", async ({ workspace, page }) => {
  await workspace.go("Configurações")
  await page.getByRole("button", { name: "Escuro", exact: true }).click()
  await expect(page.locator("html")).toHaveClass(/dark/)
  await page.getByRole("button", { name: "Usar #8B5CF6", exact: true }).click()
  await page.getByRole("textbox", { name: "Código hexadecimal da cor de destaque", exact: true }).fill("#123456")
  await expect(page.locator("html")).toHaveCSS("--brand", "#123456")
  await page.getByRole("tab", { name: "EN", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Settings", exact: true })).toBeVisible()
  await workspace.restart()
  page = workspace.page
  await workspace.go("Settings")
  await expect(page.locator("html")).toHaveClass(/dark/)
  await expect(page.locator("html")).toHaveCSS("--brand", "#123456")
  await page.getByRole("tab", { name: "PT", exact: true }).click()
  await page.getByRole("button", { name: "Claro", exact: true }).click()
  await expect(page.locator("html")).not.toHaveClass(/dark/)
  await page.getByRole("button", { name: "Restaurar", exact: true }).click()
  await expect(page.locator("html")).toHaveCSS("--brand", "#FF892B")
  await page.getByRole("tab", { name: "GitHub", exact: true }).click()
  await expect(page.getByLabel("Token de acesso pessoal", { exact: true })).toBeVisible()
  await page.getByRole("tab", { name: "Atualizações", exact: true }).click()
  await expect(page).toHaveURL(/tab=updates/)
  await expect(page.getByRole("button", { name: "Verificar atualizações", exact: true })).toBeDisabled()
})

test("settings: startup files are isolated, background close and tray reopen", async ({ workspace, page }) => {
  await workspace.go("Configurações")
  const login = page.getByRole("switch", { name: "Iniciar o Life Board quando eu entrar no sistema", exact: true })
  await login.click()
  const path = join(workspace.home, "config/autostart/dev.nathanmota.lifeboard.desktop")
  await expect.poll(() => existsSync(path)).toBe(true)
  expect(readFileSync(path, "utf8")).toContain("--hidden")
  await page.getByRole("switch", { name: "Continuar em segundo plano ao fechar a janela", exact: true }).click()
  await workspace.app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close())
  await expect.poll(() => workspace.app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible())).toBe(false)
  await workspace.app.evaluate(({ app }) => app.emit("activate"))
  await expect.poll(() => workspace.app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible())).toBe(true)
  await login.click()
  await expect.poll(() => existsSync(path)).toBe(false)
  await workspace.restart(true)
  page = workspace.page
  await workspace.go("Configurações")
  await expect(page.getByRole("switch", { name: "Continuar em segundo plano ao fechar a janela", exact: true })).toBeChecked()
})
